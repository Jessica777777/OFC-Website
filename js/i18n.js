const OFC_LANG_KEY = 'ofc-lang';

function ofcGetLang() {
  try {
    const v = localStorage.getItem(OFC_LANG_KEY);
    return LANGS.includes(v) ? v : 'zh';
  } catch (e) {
    return 'zh';
  }
}

function ofcSetLang(lang) {
  if (!LANGS.includes(lang)) lang = 'zh';
  try { localStorage.setItem(OFC_LANG_KEY, lang); } catch (e) { /* ignore (private browsing, etc.) */ }
  applyI18n(lang);
  // v26: lets any dynamically-generated UI (e.g. the carousel's JS-built
  // dot buttons and play/pause label in js/main.js) re-read I18N and
  // relabel itself — applyI18n() above only walks data-i18n-* elements
  // that already exist in the DOM at load time.
  document.dispatchEvent(new CustomEvent('ofc:langchange'));
}

function applyI18n(lang) {
  const dict = I18N[lang] || I18N.zh;
  window.OFC_I18N_CURRENT = lang;
  document.documentElement.lang = lang === 'en' ? 'en' : (lang === 'ja' ? 'ja' : 'zh-Hant');

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const val = dict[key];
    if (val === undefined) return;
    if (el.tagName === 'TITLE') {
      el.textContent = val;
      document.title = val;
    } else {
      el.innerHTML = val;
    }
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    const val = dict[el.getAttribute('data-i18n-aria-label')];
    if (val !== undefined) el.setAttribute('aria-label', val);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    const val = dict[el.getAttribute('data-i18n-alt')];
    if (val !== undefined) el.setAttribute('alt', val);
  });
  document.querySelectorAll('[data-i18n-content]').forEach((el) => {
    const val = dict[el.getAttribute('data-i18n-content')];
    if (val !== undefined) el.setAttribute('content', val);
  });

  document.querySelectorAll('.lang-switch button[data-lang]').forEach((btn) => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // Dropdown trigger label (v13): shows the currently selected language's
  // short label (中/EN/日) on the collapsed button, since the switch is no
  // longer three always-visible buttons but a single trigger + menu.
  document.querySelectorAll('.lang-switch-label').forEach((el) => {
    el.textContent = LANG_LABEL[lang] || LANG_LABEL.zh;
  });
}

/* Dropdown open/close (v13): each .lang-switch now holds a
   .lang-switch-toggle trigger button plus a .lang-switch-menu list (fixed
   order EN / 中 / 日, per spec) instead of three permanently-visible
   buttons. Clicking the trigger toggles an "open" class that the CSS uses
   to reveal the menu below it; picking a language applies it and closes
   the menu; clicking anywhere else closes any open menu. */
function initLangToggle() {
  const lang = ofcGetLang();
  applyI18n(lang);

  function closeAllExcept(except) {
    document.querySelectorAll('.lang-switch.open').forEach((g) => {
      if (g === except) return;
      g.classList.remove('open');
      const t = g.querySelector('.lang-switch-toggle');
      if (t) t.setAttribute('aria-expanded', 'false');
    });
  }

  document.querySelectorAll('.lang-switch').forEach((group) => {
    const toggleBtn = group.querySelector('.lang-switch-toggle');
    if (toggleBtn) {
      toggleBtn.addEventListener('click', (e) => {
        e.stopPropagation();
        const isOpen = group.classList.toggle('open');
        toggleBtn.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
        closeAllExcept(isOpen ? group : null);
      });
    }
    group.querySelectorAll('button[data-lang]').forEach((btn) => {
      btn.addEventListener('click', () => {
        ofcSetLang(btn.getAttribute('data-lang'));
        group.classList.remove('open');
        if (toggleBtn) toggleBtn.setAttribute('aria-expanded', 'false');
      });
    });
  });

  // Click/tap anywhere outside an open dropdown closes it.
  document.addEventListener('click', () => closeAllExcept(null));
}

document.addEventListener('DOMContentLoaded', initLangToggle);
